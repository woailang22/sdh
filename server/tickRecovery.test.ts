import { expect, it } from 'vitest';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { mkdtempSync } from 'node:fs';
import { createServer, type AddressInfo } from 'node:net';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import Database from 'better-sqlite3';
import { WebSocket } from 'ws';
import { createDb } from './db';
import { resolveGuest } from './identity';
import { GameWorld, type WorldRules } from './worldState';
import { makeItem } from '../src/game/items';

const delay = (ms: number) => new Promise(resolve => setTimeout(resolve, ms));
const rules: WorldRules = { nodeAt: () => undefined, nodesNear: () => [], buildingsNear: () => [], monstersNear: () => [], campSiteAllowed: () => false, migrate: (_map, x, y) => ({ mapId: 'world', x, y }) };

it('keeps the production server live through rejected shared ticks and preserves a private shot across retry and restart', async () => {
  const file = join(mkdtempSync(join(tmpdir(), 'sdc-tick-recovery-')), 'world.sqlite'), db = createDb(file);
  const owner = resolveGuest(db), raider = resolveGuest(db), game = new GameWorld(db, rules, () => 10000), mapId = 'home_recovery';
  game.connect(owner.playerId, '主人'); game.connect(raider.playerId, '攻击者');
  game.state.camps[mapId] = { id: mapId, ownerId: owner.playerId, ownerName: '主人', mapId: 'world', x: 100, y: 100, members: [], size: 64 };
  const p = game.state.players[raider.playerId]; Object.assign(p, { mapId, x: 4, y: 0, shield: 0 });
  p.equipment.weapon = makeItem('rifle', 1); p.resources.ammo = 10;
  for (const [id, type, x] of [['core', 'anchor_core', 0], ['turret', 'turret', 3], ['spikes', 'spikes', 4.5]] as const) game.state.buildings[id] = { id, type, x, y: 0, hp: 300, maxHp: 300, level: 1, name: id, ownerId: owner.playerId, mapId };
  game.state.ammo.turret = 3;
  game.state.drops.expired = { id: 'expired', name: '旧包', mapId: 'world', x: 0, y: 0, items: [], expiresAt: 10000 };
  game.disconnect(owner.playerId); game.disconnect(raider.playerId); db.setMeta('public-house-layout', '2');
  const probe = createServer(); await new Promise<void>(resolve => probe.listen(0, '127.0.0.1', resolve));
  const port = (probe.address() as AddressInfo).port; await new Promise<void>((resolve, reject) => probe.close(error => error ? reject(error) : resolve()));
  const source = `import { GameWorld } from ${JSON.stringify(pathToFileURL(resolve('server/worldState.ts')).href)};
    let clock=10000,armed=false;Date.now=()=>clock;process.on('message',m=>{if(m.arm)armed=true;if(m.clock)clock=m.clock;});
    const tick=GameWorld.prototype.tick;GameWorld.prototype.tick=function(){if(!armed)return false;try{return tick.call(this)}catch(error){process.send({failed:true,hp:this.state.players[${JSON.stringify(raider.playerId)}].hp,carriedAmmo:this.state.players[${JSON.stringify(raider.playerId)}].resources.ammo,turretAmmo:this.state.ammo.turret,spikesHp:this.state.buildings.spikes.hp,cooldowns:this.state.defenseAt});throw error;}};
    await import(${JSON.stringify(pathToFileURL(resolve('server.ts')).href)});`;
  const child = spawn(process.execPath, ['--import', 'tsx', '--input-type=module', '--eval', source], { cwd: process.cwd(), windowsHide: true, env: { ...process.env, NODE_ENV: 'production', PORT: String(port), DB_PATH: file }, stdio: ['ignore', 'pipe', 'pipe', 'ipc'] });
  const exited = once(child, 'exit'), control = new Database(file), failures: any[] = [], messages: any[] = [];
  let started = false, stderr = '', ws: WebSocket | undefined, stopped = false;
  child.stdout!.on('data', c => { started ||= String(c).includes('[Rift Walker]'); }); child.stderr!.on('data', c => { stderr += String(c); });
  child.on('message', m => { failures.push(m); });
  const until = async (predicate: () => boolean) => { const end = Date.now() + 5000; while (Date.now() < end) { if (child.exitCode !== null || child.signalCode !== null) throw Error('Production server stopped during recovery'); if (predicate()) return; await delay(5); } throw Error('Tick recovery timed out'); };
  const stop = async () => { if (!stopped) { stopped = true; child.kill('SIGKILL'); await exited; } };
  const stateOf = (m: any) => m.type === 'game_state_patch' ? m.payload.state : m.type === 'game_state' ? m.payload : undefined;
  try {
    await until(() => started); const url = 'http://127.0.0.1:' + port;
    ws = new WebSocket(url.replace('http', 'ws') + '/ws', { headers: { Cookie: 'sdc_guest=' + raider.token, Origin: url } });
    ws.on('message', raw => messages.push(JSON.parse(String(raw)))); ws.on('error', () => {});
    await once(ws, 'open'); await until(() => messages.some(m => m.type === 'init'));
    const send = (type: string, payload: unknown) => ws!.send(JSON.stringify({ type, payload }));
    send('state_sync', { version: 1 }); await until(() => messages.some(m => m.type === 'game_state_patch'));
    control.exec("CREATE TRIGGER reject_tick BEFORE UPDATE ON meta WHEN NEW.k='authoritative-world-v2' BEGIN SELECT RAISE(ABORT, 'qa shared tick failure'); END");
    child.send({ arm: true }); await until(() => failures.length > 0);
    expect(failures.at(-1)).toMatchObject({ hp: 100, carriedAmmo: 10, turretAmmo: 3, spikesHp: 300, cooldowns: {} });
    send('ping', {}); await until(() => messages.some(m => m.type === 'pong')); expect((await fetch(url + '/api/health')).ok).toBe(true);
    send('game_action', { action: 'fire', requestId: 'paid-during-failure' });
    await until(() => messages.some(m => stateOf(m)?.requestId === 'paid-during-failure'));
    const reply = messages.map(stateOf).find(s => s?.requestId === 'paid-during-failure');
    expect(reply.error).toBeUndefined(); expect(reply.player.hp).toBe(100); expect(reply.player.resources.ammo).toBe(9);
    await until(() => failures.some(s => s.carriedAmmo === 9));
    expect(failures.at(-1)).toMatchObject({ hp: 100, carriedAmmo: 9, turretAmmo: 3, spikesHp: 300, cooldowns: {} });
    expect(messages.map(stateOf).filter(Boolean).every(s => s.player.hp === 100)).toBe(true);
    expect(JSON.parse(db.getMeta('authoritative-world-v2')!).drops).toHaveProperty('expired');
    const commit = JSON.parse(db.listWorldPlayerCommits().find(c => c.id === raider.playerId)!.data);
    expect(commit.player.resources.ammo).toBe(9); expect(commit.handled).toEqual(['paid-during-failure']);
    control.exec('DROP TRIGGER reject_tick'); await until(() => messages.map(stateOf).some(s => s?.player.hp === 80));
    child.send({ clock: 11000 }); await until(() => messages.map(stateOf).some(s => s?.player.hp === 60));
    await stop(); const restored = new GameWorld(createDb(file), rules, () => 11000);
    expect(restored.state.players[raider.playerId].hp).toBe(60); expect(restored.state.ammo.turret).toBe(1);
    expect(restored.state.buildings.spikes.hp).toBe(280); expect(restored.state.drops).toEqual({});
    expect(restored.state.handled[raider.playerId]).toEqual(['paid-during-failure']);
    expect(restored.state.defenseAt).toEqual({ turret: 11000, spikes: 11000 });
    restored.tick(); expect(restored.state.ammo.turret).toBe(1);
    expect(restored.actionPlayer(raider.playerId, { action: 'fire', requestId: 'paid-during-failure' }).player.resources.ammo).toBe(9);
    expect(stderr).toContain('[world] simulation tick failed'); expect(stderr).toContain('qa shared tick failure');
    expect(control.pragma('integrity_check', { simple: true })).toBe('ok');
  } finally { await stop(); ws?.terminate(); control.close(); }
}, 20000);
